"""
StockSense AI – physical database schema.

Portable ANSI-SQL DDL: runs unchanged on SQLite (demo) and PostgreSQL
(production). Money columns are NUMERIC, never FLOAT, in the production path.

Design rules enforced here
--------------------------
1. ``stock_event`` is APPEND-ONLY. There is no UPDATE/DELETE path in the
   application layer; a mis-keyed movement is corrected by inserting a new
   ADJUSTMENT event that references it.
2. Every event carries a globally unique ``event_id`` (UUID4 generated by the
   *originating store*) which is UNIQUE in the central table. That is the
   mechanism that makes re-sent offline batches idempotent.
3. ``stock_on_hand`` is a derived cache. It can be thrown away and rebuilt
   from the ledger with ``inventory.recompute_stock_on_hand()``.
"""
