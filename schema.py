# Reporting view – proves stock_on_hand is derived from the append-only ledger.
VIEWS: list[str] = [
    """
    CREATE VIEW IF NOT EXISTS v_ledger_stock AS
    SELECT store_id, sku_id, SUM(quantity_delta) AS ledger_qty,
           MAX(occurred_at) AS last_event_at, COUNT(*) AS event_count
    FROM stock_event GROUP BY store_id, sku_id
    """,
    """
    CREATE VIEW IF NOT EXISTS v_inventory_enriched AS
    SELECT s.store_code, s.store_name, s.region, s.store_format,
           k.sku_code, k.barcode, k.product_name, k.unit_cost, k.selling_price,
           k.reorder_level, k.safety_stock, c.category_name,
           sup.supplier_name, sup.lead_time_days,
           soh.on_hand_qty, soh.reserved_qty, soh.in_transit_qty,
           (soh.on_hand_qty * k.unit_cost) AS stock_value,
           CASE
             WHEN soh.on_hand_qty <= 0 THEN 'Out of Stock'
             WHEN soh.on_hand_qty <= k.safety_stock THEN 'Critical Stock'
             WHEN soh.on_hand_qty <= k.reorder_level THEN 'Low Stock'
             ELSE 'In Stock'
           END AS stock_status
    FROM stock_on_hand soh
    JOIN stores s ON s.store_id = soh.store_id
    JOIN sku k ON k.sku_id = soh.sku_id
    JOIN product_categories c ON c.category_id = k.category_id
    JOIN suppliers sup ON sup.supplier_id = k.supplier_id
    """,
]


def create_schema(drop_first: bool = False) -> None:
    """Create every table, index and view."""
    if drop_first:
        drop_all()
    engine = get_engine()
    with engine.begin() as conn:
        raw = conn.connection.driver_connection
        cur = raw.cursor()
        for statement in DDL + VIEWS:
            cur.execute(statement)
        raw.commit()
        cur.close()
    log.info("schema created (%d objects)", len(DDL) + len(VIEWS))


def drop_all() -> None:
    engine = get_engine()
    with engine.begin() as conn:
        raw = conn.connection.driver_connection
        cur = raw.cursor()
        cur.execute("PRAGMA foreign_keys=OFF")
        for (name,) in cur.execute(
            "SELECT name FROM sqlite_master WHERE type IN ('view','table') "
            "AND name NOT LIKE 'sqlite_%'"
        ).fetchall():
            kind = "VIEW" if name.startswith("v_") else "TABLE"
            cur.execute(f"DROP {kind} IF EXISTS {name}")
        cur.execute("PRAGMA foreign_keys=ON")
        raw.commit()
        cur.close()
    log.info("schema dropped")


if __name__ == "__main__":  # pragma: no cover
    create_schema(drop_first=True)
    print("Schema created at", __import__("config").DB_PATH)
