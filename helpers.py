"""Small generic helpers: ids, hashing, dates, logging, JSON safety."""
from __future__ import annotations

import hashlib
import json
import logging
import os
import sys
import uuid
from datetime import date, datetime, timedelta
from typing import Any

# --------------------------------------------------------------------------
# Logging
# --------------------------------------------------------------------------
def get_logger(name: str = "stocksense", level: int = logging.INFO) -> logging.Logger:
    logger = logging.getLogger(name)
    if not logger.handlers:
        h = logging.StreamHandler(sys.stdout)
        h.setFormatter(logging.Formatter("%(asctime)s | %(levelname)-7s | %(name)s | %(message)s",
                                         datefmt="%H:%M:%S"))
        logger.addHandler(h)
        logger.setLevel(level)
    return logger


# --------------------------------------------------------------------------
# Identity
# --------------------------------------------------------------------------
def new_event_id() -> str:
    """Idempotency key for a stock event – generated by the ORIGINATING node."""
    return str(uuid.uuid4())


def new_batch_id(store_code: str) -> str:
    stamp = datetime.utcnow().strftime("%Y%m%d%H%M%S%f")[:-3]
    return f"SYNC-{store_code}-{stamp}-{uuid.uuid4().hex[:6]}"


def alert_ref(store_code: str, sku_code: str, seq: int) -> str:
    return f"ALT-{store_code.split('-')[-1]}-{sku_code[-3:]}-{seq:05d}"


